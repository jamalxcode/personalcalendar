let LANG = "en";
function tr(s) {
  if (LANG !== "ar" || s == null) return s;
  const k = String(s).trim();
  if (AR[k]) return AR[k];
  for (const [re, rep] of AR_PATTERNS) if (re.test(k)) return k.replace(re, rep);
  return s;
}
const ORIG = new WeakMap();
function trNode(n) {
  if (n.nodeType === 3) {
    // if the text changed since we translated it, the new text is the original
    if (ORIG.has(n) && n.nodeValue !== ORIG.get(n).shown) ORIG.delete(n);
    const raw = ORIG.has(n) ? ORIG.get(n).raw : n.nodeValue;
    if (!raw.trim()) return;
    const want = LANG === "ar" ? raw.replace(raw.trim(), tr(raw.trim())) : raw;
    if (want !== n.nodeValue) { n.nodeValue = want; }
    if (want !== raw) ORIG.set(n, { raw, shown: want }); else ORIG.delete(n);
    return;
  }
  if (n.nodeType !== 1 || n.tagName === "SCRIPT" || n.tagName === "STYLE") return;
  for (const a of ["title", "placeholder", "aria-label"]) {
    if (!n.hasAttribute(a)) continue;
    const key = "data-orig-" + a;
    if (!n.hasAttribute(key)) n.setAttribute(key, n.getAttribute(a));
    n.setAttribute(a, LANG === "ar" ? tr(n.getAttribute(key)) : n.getAttribute(key));
  }
  if (n.tagName !== "TEXTAREA") n.childNodes.forEach(trNode);
}
let i18nObs = null;
function i18nApply(lang) {
  LANG = lang === "ar" ? "ar" : "en";
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === "ar" ? "rtl" : "ltr";
  trNode(document.body);
  if (!i18nObs) {
    i18nObs = new MutationObserver((ms) => {
      if (LANG !== "ar") return;
      for (const m of ms) {
        if (m.type === "characterData") trNode(m.target);
        else m.addedNodes.forEach(trNode);
      }
    });
    i18nObs.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
}
